let text =
  "# OriginKit inventory - rendered source studies\n\nAll COUNT installed items were read and rendered in original and editorial variants. `/playground` mounts only visible panels; each variant has its own document so CSS and IDs cannot collide. The exact draw contexts and runtime observations are in [playground-results.json](playground-results.json).\n\nPalette: ink `#0A0A0A`, graphite `#141414`, paper `#F4F2EC`, warm grey `#8C8A84`, restrained signal amber `#FFB45A`. No shaders, geometry or visual algorithms were recreated. Type-only fixes and the requested opt-in stone-intro controls are recorded in [fixes.md](fixes.md).\n\nCosts below are source-informed relative estimates, not measured frame-rate guarantees. Playground captures are desktop; mobile behavior combines the source breakpoints/controls with the production fallback policy.\n".replace(
    "COUNT",
    String(sourceCatalog.length),
  );
for (const item of sourceCatalog) {
  const n = notes[item.slug];
  text += `\n## ${item.slug}\n\n${item.signature}\n\n**Signature / layout to reuse:** ${n.layout}\n\n**Interaction / rendering:** ${n.interaction}\n\n**Performance:** ${item.cost}. ${n.mobile}\n\n**Yazhnova use:** ${n.use}\n\n**Screenshot:** [Default + editorial palette](shots/${item.slug}.png).\n\n**Public props and defaults:** ${["hero-44", "hero-55"].includes(item.slug) ? "SectionHero accepts optional typed children and artwork slots (hero-44 also accepts className); the entry forwards these props. The native visual controls are extracted below." : item.kind === "section" ? "The section export accepts no configurable props; copy/layout are hardcoded. The companion APIs below are the reusable controls. Production composes those genuine companions with its own content and layout." : "The original interfaces and default values below are extracted from the installed source. Settings not overridden keep these defaults."}\n`;
  for (const relative of n.files) {
    const file = `components/originkit/${relative}`;
    const source = fs.readFileSync(file, "utf8");
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const definitions = [];
    for (const node of ast.statements) {
      if (ts.isInterfaceDeclaration(node)) definitions.push(node.getText(ast));
      if (
        ts.isTypeAliasDeclaration(node) &&
        /Props|Centre|Dots|Marker|Network|Group|Config|Mode|Message|Font/.test(node.name.text)
      )
        definitions.push(node.getText(ast));
      if (ts.isVariableStatement(node)) {
        for (const d of node.declarationList.declarations)
          if (/DEFAULT|^defaults$|^D_(LIGHT|SHAFTS|FINISH)$/.test(d.name.getText(ast)))
            definitions.push(d.getText(ast));
      }
      if (
        ts.isFunctionDeclaration(node) &&
        node.name &&
        /RainPuddle|PlasmaRing|SectionHero|SlotMachine|LightShaftText|StarfieldButton|MovingGradientButton|CosmicBG|NeonBorder|SingleGlossySphere|StarGate|SparkLattice|PredictiveArcHorizon|FluidField|LightBloom|LightCables|DataStrings|LiquidGrid|GlitchCharReveal|LineMaskSplit|GlowBorder|CurvedLoop|StackedCarousel3D|SpotlightReveal|IOSMessageList|AuraCursor|Hairline/.test(
          node.name.text,
        )
      ) {
        const s = node.parameters.map((p) => p.getText(ast)).join(", ");
        definitions.push(`function ${node.name.text}(${s})`);
        if (node.body) {
          for (const statement of node.body.statements.slice(0, 2)) {
            if (ts.isVariableStatement(statement) && statement.getText(ast).includes("= props"))
              definitions.push(statement.getText(ast));
          }
        }
      }
    }
    if (definitions.length)
      text += `\n\`${file}\`\n\n\`\`\`ts\n${definitions.join("\n\n")}\n\`\`\`\n`;
  }
  text += `\n**Editorial overrides:** ${editorialPresets[item.slug] ? "Explicit source props:" : "Section wrapper uses monochrome filtering and palette CSS variables; the original raw section and all of its geometry stay intact."}\n`;
  if (editorialPresets[item.slug])
    text += "\n```json\n" + JSON.stringify(editorialPresets[item.slug], null, 2) + "\n```\n";
}
fs.writeFileSync("docs/inventory.md", text);
console.log(
  `Wrote the ${sourceCatalog.length}-item source inventory with exhaustive installed interfaces and defaults.`,
);
